class MultiLabelClassifier(nn.Module):
    def __init__(self, input_dim, num_labels):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(input_dim, 512),
            nn.ReLU(),
            nn.Linear(512, 512),
            nn.ReLU(),
            nn.Dropout(0.2),
            nn.Linear(512, num_labels),
        )
    def forward(self, x):
        return self.net(x)

def chunk_text(text, tokenizer, chunk_size=500, overlap=50):
    text = re.sub(r'\s+', ' ', text).strip()
    if not text:
        return []
    tokens = tokenizer.encode(text, add_special_tokens=False, truncation=False)
    chunks = []
    for i in range(0, len(tokens), chunk_size - overlap):
        ct = tokens[i:i + chunk_size]
        if len(ct) < 10: # Lowered threshold for interactive use
            continue
        chunks.append(tokenizer.decode(ct, skip_special_tokens=True))
        if i + chunk_size >= len(tokens):
            break
    if not chunks and text:
        chunks = [text]
    return chunks

class PredictionResults(Static):
    """A widget to display prediction results as a bar chart."""
    results = reactive([])

    def render(self) -> Panel:
        if not self.results:
            return Panel("Start typing to see predictions...", title="Top 10 Predictions")

        table = Table.grid(expand=True)
        table.add_column("Tag", ratio=1)
        table.add_column("Conf", width=10)
        table.add_column("Bar", ratio=1)

        for tag, conf in self.results:
            # Create a simple bar using Rich's Bar or just stylized text
            bar = Bar(size=1.0, begin=0, end=conf, color="green" if conf > 0.5 else "yellow")
            table.add_row(
                Text(tag, overflow="ellipsis", no_wrap=True),
                f"{conf:.4f}",
                bar
            )

        return Panel(table, title="Top 10 Predictions")

class PredictDocumentApp(App):
    CSS = """
    Screen {
        background: $surface;
    }
    #main-container {
        height: 1fr;
    }
    #left-pane {
        width: 60%;
        border-right: tall $primary;
        padding: 1;
    }
    #right-pane {
        width: 40%;
        padding: 1;
    }
    TextArea {
        height: 1fr;
        border: none;
    }
    """

    BINDINGS = [
        ("q", "quit", "Quit"),
        ("ctrl+s", "save", "Save Text"),
        ("ctrl+l", "clear", "Clear Input"),
    ]

    def action_clear(self) -> None:
        self.text_input.text = ""
        self.text_input.focus()

    def __init__(self, encoder_path, classifier_path):
        super().__init__()
        self.encoder_path = encoder_path
        self.classifier_path = classifier_path
        self.device = "cuda" if torch.cuda.is_available() else "cpu"
        self.model_loaded = False

    def compose(self) -> ComposeResult:
        yield Header()
        with Horizontal(id="main-container"):
            with Vertical(id="left-pane"):
                yield Static("Enter Document Text:")
                self.text_input = TextArea(placeholder="Type here...")
                yield self.text_input
            with Vertical(id="right-pane"):
                self.results_display = PredictionResults()
                yield self.results_display
        yield Footer()

    async def on_mount(self) -> None:
        self.text_input.focus()
        self.load_models()

    @work(exclusive=True, thread=True)
    def load_models(self):
        self.call_from_thread(self.update_status, "Loading models...")
        try:
            clf_data = joblib.load(self.classifier_path)
            self.encoder = SentenceTransformer(self.encoder_path).to(self.device)
            self.tokenizer = AutoTokenizer.from_pretrained(self.encoder_path, local_files_only=True)

            self.tag_ids = np.array(clf_data['tag_ids'])
            self.tag_names = clf_data.get('tag_names', [f"tag_{t}" for t in self.tag_ids])

            self.classifier = MultiLabelClassifier(clf_data['input_dim'], clf_data['num_labels']).to(self.device)
            self.classifier.load_state_dict(clf_data['model_state'])
            self.classifier.eval()
            self.model_loaded = True
            self.call_from_thread(self.update_status, "Models loaded. Ready.")
        except Exception as e:
            self.call_from_thread(self.update_status, f"Error loading models: {e}")

    def update_status(self, message: str):
        self.sub_title = message

    def on_text_area_changed(self, event: TextArea.Changed) -> None:
        if self.model_loaded:
            # The @work(exclusive=True) handles cancelling previous tasks
            self.run_prediction(event.text_area.text)

    @work(exclusive=True, thread=True)
    def run_prediction(self, text: str):
        if not text.strip():
            self.call_from_thread(self.update_results, [])
            return

        import time
        # Small sleep to avoid thrashing during rapid typing
        time.sleep(0.1)

        try:
            chunks = chunk_text(text, self.tokenizer)
            if not chunks:
                self.call_from_thread(self.update_results, [])
                return

            with torch.no_grad():
                emb = self.encoder.encode(chunks, convert_to_tensor=True, show_progress_bar=False)
                probs = torch.sigmoid(self.classifier(emb)).cpu().numpy()

            doc_probs = probs.max(axis=0)
            top_idx = np.argsort(doc_probs)[::-1][:10]

            results = []
            for idx in top_idx:
                results.append((self.tag_names[idx], float(doc_probs[idx])))

            self.call_from_thread(self.update_results, results)
        except Exception as e:
            pass

    def update_results(self, results):
        self.results_display.results = results

